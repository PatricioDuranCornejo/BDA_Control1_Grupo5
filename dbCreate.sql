--1. Crear la base de datos de clínicas veterinarias, Control 1 - Grupo 5.

DROP DATABASE IF EXISTS clinicas_veterinarias;
CREATE DATABASE clinicas_veterinarias
    ENCODING 'UTF8';

--2. Crear los catálogos de región y comuna.
CREATE TABLE region (
    id      BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(64)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_region_nombre UNIQUE (nombre)
);

CREATE TABLE comuna (
    id         BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(64)  NOT NULL,
    id_region  BIGINT       NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_comuna_nombre UNIQUE (nombre),
    CONSTRAINT fk_comuna_region FOREIGN KEY (id_region) REFERENCES region (id)
);

--3. Crear los catálogos de especie y raza.
CREATE TABLE especie (
    id    BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tipo  VARCHAR(32)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_especie_tipo UNIQUE (tipo)
);

CREATE TABLE raza (
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tipo        VARCHAR(32)  NOT NULL,
    id_especie  BIGINT       NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_raza_especie_tipo UNIQUE (id_especie, tipo),
    CONSTRAINT fk_raza_especie FOREIGN KEY (id_especie) REFERENCES especie (id)
);

--4. Crear clientes y mascotas.
CREATE TABLE cliente (
    id         BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    rut        VARCHAR(16)  NOT NULL,
    nombres    VARCHAR(64)  NOT NULL,
    apellidos  VARCHAR(64)  NOT NULL,
    id_comuna  BIGINT       NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_cliente_rut UNIQUE (rut),
    CONSTRAINT fk_cliente_comuna FOREIGN KEY (id_comuna) REFERENCES comuna (id)
);

CREATE TABLE mascota (
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(64)  NOT NULL,
    id_raza     BIGINT       NOT NULL,
    id_cliente  BIGINT       NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_mascota_raza    FOREIGN KEY (id_raza)    REFERENCES raza (id),
    CONSTRAINT fk_mascota_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id)
);

--5. Crear sucursales, sueldos, empleados y sus asignaciones.
CREATE TABLE sucursal (
    id         BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(64)   NOT NULL,
    direccion  VARCHAR(128)  NOT NULL,
    id_comuna  BIGINT        NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_sucursal_nombre UNIQUE (nombre),
    CONSTRAINT fk_sucursal_comuna FOREIGN KEY (id_comuna) REFERENCES comuna (id)
);

CREATE TABLE sueldo (
    id     BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    monto  DECIMAL(12,2)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_sueldo_monto CHECK (monto > 0)
);

CREATE TABLE empleado (
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    rut         VARCHAR(16)  NOT NULL,
    nombres     VARCHAR(64)  NOT NULL,   
    apellidos   VARCHAR(64)  NOT NULL,   
    cargo       VARCHAR(32)  NOT NULL,
    id_sueldo   BIGINT       NOT NULL,   
    PRIMARY KEY (id),
    CONSTRAINT uq_empleado_rut UNIQUE (rut),
    CONSTRAINT ck_empleado_cargo CHECK (cargo IN ('Veterinario','Asistente','Recepcionista','Administrativo')),
    CONSTRAINT fk_empleado_sueldo FOREIGN KEY (id_sueldo) REFERENCES sueldo (id)
);

CREATE TABLE sucursal_empleado (
    id                      BIGINT  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal             BIGINT  NOT NULL,
    id_empleado             BIGINT  NOT NULL,
    horario_atencion_inicio TIME    NOT NULL,
    horario_atencion_fin    TIME    NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_sucursal_empleado UNIQUE (id_sucursal, id_empleado),
    CONSTRAINT ck_se_horario CHECK (horario_atencion_fin > horario_atencion_inicio),
    CONSTRAINT fk_se_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id),
    CONSTRAINT fk_se_empleado FOREIGN KEY (id_empleado) REFERENCES empleado (id)
);

--6. Crear tipos de atención, atenciones y participación de empleados.
CREATE TABLE tipo_atencion (
    id    BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tipo  VARCHAR(64)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_tipo_atencion_tipo UNIQUE (tipo)
);

CREATE TABLE atencion (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    id_tipo         BIGINT         NOT NULL,
    fecha_atencion  DATE           NOT NULL,
    costo_total     DECIMAL(12,2)  NOT NULL,
    id_mascota      BIGINT         NOT NULL,
    id_sucursal     BIGINT         NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_atencion_costo CHECK (costo_total >= 0),
    CONSTRAINT fk_atencion_tipo     FOREIGN KEY (id_tipo)     REFERENCES tipo_atencion (id),
    CONSTRAINT fk_atencion_mascota  FOREIGN KEY (id_mascota)  REFERENCES mascota (id),
    CONSTRAINT fk_atencion_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id)
);

CREATE TABLE atencion_empleado (
    id           BIGINT  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    id_atencion  BIGINT  NOT NULL,
    id_empleado  BIGINT  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_atencion_empleado UNIQUE (id_atencion, id_empleado),
    CONSTRAINT fk_ae_atencion FOREIGN KEY (id_atencion) REFERENCES atencion (id),
    CONSTRAINT fk_ae_empleado FOREIGN KEY (id_empleado) REFERENCES empleado (id)
);

--7. Registrar pagos; una atención puede tener varios pagos parciales.
CREATE TABLE pago (
    id           BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    id_atencion  BIGINT         NOT NULL,
    fecha_pago   DATE           NOT NULL,
    monto        DECIMAL(12,2)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT fk_pago_atencion FOREIGN KEY (id_atencion) REFERENCES atencion (id)
);

CREATE TABLE medicamento (
    id          BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(64)    NOT NULL,
    fabricante  VARCHAR(64)    NOT NULL,
    precio      DECIMAL(12,2)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_medicamento_precio CHECK (precio >= 0)
);

--8. Crear recetas; una atención puede tener como máximo una receta propia.
CREATE TABLE receta (
    id           BIGINT  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    id_atencion  BIGINT  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_receta_atencion UNIQUE (id_atencion),
    CONSTRAINT fk_receta_atencion FOREIGN KEY (id_atencion) REFERENCES atencion (id)
);

CREATE TABLE receta_medicamento (
    id              BIGINT  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    id_receta       BIGINT  NOT NULL,
    id_medicamento  BIGINT  NOT NULL,
    cantidad        INT     NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_receta_medicamento UNIQUE (id_receta, id_medicamento),
    CONSTRAINT ck_rm_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_rm_receta      FOREIGN KEY (id_receta)      REFERENCES receta (id),
    CONSTRAINT fk_rm_medicamento FOREIGN KEY (id_medicamento) REFERENCES medicamento (id)
);

CREATE INDEX idx_atencion_fecha ON atencion (fecha_atencion);
CREATE INDEX idx_pago_fecha     ON pago (fecha_pago);
